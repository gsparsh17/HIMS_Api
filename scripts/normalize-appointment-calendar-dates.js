#!/usr/bin/env node
'use strict';

require('dotenv').config();
const fs = require('fs');
const mongoose = require('mongoose');
const {
  DEFAULT_HOSPITAL_TIME_ZONE,
  hospitalDateKey,
  dateKeyToStorageDate,
  dateKeyDayName,
  calendarDayKey,
  parseHospitalDateTime,
  formatHospitalTime,
  canonicalBookingFingerprint
} = require('../utils/hospitalDateTime');

const args = process.argv.slice(2);
const argValue = (name) => {
  const prefix = `--${name}=`;
  const hit = args.find((item) => item.startsWith(prefix));
  return hit ? hit.slice(prefix.length) : null;
};
const hasFlag = (name) => args.includes(`--${name}`);

const APPLY = hasFlag('apply');
const REPAIR_LEGACY_WALL_CLOCK = hasFlag('repair-legacy-wall-clock');
const HOSPITAL_ID = argValue('hospital-id');
const ALL_HOSPITALS = hasFlag('all-hospitals');
const REPORT_PATH = argValue('report');
const CLI_TIME_ZONE = argValue('timezone');
const REPAIR_SOURCES = new Set(
  String(argValue('repair-sources') || '')
    .split(',')
    .map((value) => value.trim())
    .filter(Boolean)
);

if (!HOSPITAL_ID && !ALL_HOSPITALS) {
  console.error('Choose a scope: --hospital-id=<ObjectId> or --all-hospitals');
  process.exit(2);
}
if (HOSPITAL_ID && !mongoose.isValidObjectId(HOSPITAL_ID)) {
  console.error('--hospital-id must be a valid ObjectId');
  process.exit(2);
}
if (REPAIR_LEGACY_WALL_CLOCK && REPAIR_SOURCES.size === 0) {
  console.error('--repair-legacy-wall-clock requires --repair-sources=SOURCE1,SOURCE2');
  process.exit(2);
}

const mongoUri = process.env.MONGO_URI || process.env.MONGODB_URI;
if (!mongoUri) {
  console.error('MONGO_URI (or MONGODB_URI) is required');
  process.exit(2);
}

const DATE_KEY_RE = /^\d{4}-\d{2}-\d{2}$/;
const explicitZeroOffsetWallClock = /(T\d{2}:\d{2}(?::\d{2}(?:\.\d+)?)?)\+00:00$/i;

function idText(value) {
  if (value == null) return '';
  return String(value);
}

function bookingFingerprintStartText(fingerprint) {
  const fields = String(fingerprint || '').split('|');
  return fields.length >= 6 ? fields[5] : '';
}

function isLegacyUtcWallClockCandidate(appointment, dateKey, timeZone) {
  if (appointment.type !== 'time-based' || !appointment.start_time) return false;
  const startText = bookingFingerprintStartText(appointment.bookingFingerprint);
  // Only an explicit +00:00 fingerprint is treated as strong legacy wall-clock
  // evidence. Canonical fingerprints generated by this migration intentionally
  // end in Z; treating Z as legacy evidence makes a post-normalization audit
  // falsely flag every normal time-based appointment.
  if (!explicitZeroOffsetWallClock.test(startText)) return false;
  const fingerprintDate = startText.slice(0, 10);
  const stored = new Date(appointment.start_time);
  if (Number.isNaN(stored.getTime()) || fingerprintDate !== dateKey) return false;

  // Stronger signal: the stored UTC clock exactly equals the UTC-tagged wall clock.
  const sourceClock = startText.slice(11, 16);
  const storedUtcClock = `${String(stored.getUTCHours()).padStart(2, '0')}:${String(stored.getUTCMinutes()).padStart(2, '0')}`;
  const hospitalClock = formatHospitalTime(stored, timeZone);
  return sourceClock === storedUtcClock && hospitalClock !== sourceClock;
}

function mergeBreaks(target, incoming) {
  const seen = new Set((target || []).map((row) => `${new Date(row.startTime).toISOString()}|${new Date(row.endTime).toISOString()}|${row.reason || ''}`));
  for (const row of incoming || []) {
    const start = new Date(row.startTime);
    const end = new Date(row.endTime);
    if (Number.isNaN(start.getTime()) || Number.isNaN(end.getTime())) continue;
    const key = `${start.toISOString()}|${end.toISOString()}|${row.reason || ''}`;
    if (!seen.has(key)) {
      target.push(row);
      seen.add(key);
    }
  }
}

function mergeDoctorRows(targetDay, incomingDay) {
  const byDoctor = new Map((targetDay.doctors || []).map((row) => [idText(row.doctorId), row]));
  for (const incoming of incomingDay.doctors || []) {
    const key = idText(incoming.doctorId);
    if (!key) continue;
    const existing = byDoctor.get(key);
    if (!existing) {
      const clone = { ...incoming, bookedAppointments: [], bookedPatients: [], breaks: [...(incoming.breaks || [])] };
      targetDay.doctors.push(clone);
      byDoctor.set(key, clone);
    } else {
      existing.breaks = existing.breaks || [];
      mergeBreaks(existing.breaks, incoming.breaks || []);
    }
  }
}

async function normalizeHospital(hospital) {
  const hospitalId = hospital._id;
  const timeZone = CLI_TIME_ZONE || hospital.timezone || DEFAULT_HOSPITAL_TIME_ZONE;
  const appointmentsCollection = mongoose.connection.collection('appointments');
  const calendarsCollection = mongoose.connection.collection('calendars');

  const appointments = await appointmentsCollection.find({ hospital_id: hospitalId }).toArray();
  const appointmentUpdates = [];
  const legacyCandidates = [];
  const normalizedAppointments = [];

  for (const appointment of appointments) {
    let dateKey;
    try {
      dateKey = DATE_KEY_RE.test(String(appointment.appointment_date_key || ''))
        ? appointment.appointment_date_key
        : hospitalDateKey(appointment.appointment_date, timeZone);
    } catch (error) {
      legacyCandidates.push({
        appointmentId: idText(appointment._id),
        issue: 'INVALID_APPOINTMENT_DATE',
        value: appointment.appointment_date,
        error: error.message
      });
      continue;
    }

    let startTime = appointment.start_time ? new Date(appointment.start_time) : null;
    let endTime = appointment.end_time ? new Date(appointment.end_time) : null;
    if (startTime && Number.isNaN(startTime.getTime())) startTime = null;
    if (endTime && Number.isNaN(endTime.getTime())) endTime = null;
    const candidate = isLegacyUtcWallClockCandidate(appointment, dateKey, timeZone);
    let repairEligible = false;
    if (candidate) {
      const originalStartText = bookingFingerprintStartText(appointment.bookingFingerprint);
      legacyCandidates.push({
        appointmentId: idText(appointment._id),
        token: appointment.token,
        source: appointment.submissionSource,
        dateKey,
        storedStart: startTime?.toISOString(),
        fingerprintStart: originalStartText,
        storedHospitalClock: formatHospitalTime(startTime, timeZone),
        proposedHospitalClock: originalStartText.slice(11, 16),
        repairEligible: REPAIR_LEGACY_WALL_CLOCK && REPAIR_SOURCES.has(String(appointment.submissionSource || ''))
      });

      repairEligible = REPAIR_LEGACY_WALL_CLOCK && REPAIR_SOURCES.has(String(appointment.submissionSource || ''));
      if (repairEligible) {
        const wallClock = originalStartText.slice(11, 19);
        const repairedStart = parseHospitalDateTime(wallClock, dateKey, timeZone);
        const duration = Number(appointment.duration || ((endTime - startTime) / 60000) || 10);
        startTime = repairedStart;
        endTime = new Date(repairedStart.getTime() + duration * 60000);
      }
    }

    // Preserve the original fingerprint for suspicious rows unless the
    // operator explicitly repairs them. That fingerprint is evidence for a
    // later reviewed repair and must not be destroyed by the safe normalize pass.
    const fingerprint = candidate && !repairEligible
      ? appointment.bookingFingerprint
      : canonicalBookingFingerprint({
        hospitalId,
        patientId: appointment.patient_id,
        doctorId: appointment.doctor_id,
        appointmentDateKey: dateKey,
        type: appointment.type,
        startTime
      });

    const set = {
      appointment_date_key: dateKey,
      appointment_date: dateKeyToStorageDate(dateKey),
      scheduled_timezone: timeZone,
      bookingFingerprint: fingerprint
    };
    if (repairEligible) {
      set.start_time = startTime;
      set.end_time = endTime;
    }

    appointmentUpdates.push({
      updateOne: { filter: { _id: appointment._id, hospital_id: hospitalId }, update: { $set: set } }
    });
    normalizedAppointments.push({ ...appointment, ...set });
  }

  const calendar = await calendarsCollection.findOne({ hospitalId });
  let calendarSummary = { found: false, originalDays: 0, normalizedDays: 0, duplicateSemanticDays: 0, reservationsRebuilt: 0 };
  let normalizedCalendar = null;

  if (calendar) {
    calendarSummary.found = true;
    calendarSummary.originalDays = Array.isArray(calendar.days) ? calendar.days.length : 0;
    const byDate = new Map();

    for (const day of calendar.days || []) {
      let key;
      try {
        key = calendarDayKey(day, timeZone);
      } catch (_error) {
        continue;
      }
      if (byDate.has(key)) {
        calendarSummary.duplicateSemanticDays += 1;
        mergeDoctorRows(byDate.get(key), day);
      } else {
        const copy = {
          ...day,
          date: dateKeyToStorageDate(key),
          dateKey: key,
          dayName: dateKeyDayName(key),
          doctors: (day.doctors || []).map((row) => ({
            ...row,
            bookedAppointments: [],
            bookedPatients: [],
            breaks: [...(row.breaks || [])]
          }))
        };
        byDate.set(key, copy);
      }
    }

    // Appointment is the source of truth for reservations. Rebuild only dates
    // that exist in the rolling hospital calendar; historical appointments are
    // intentionally not used to grow the calendar indefinitely.
    for (const appointment of normalizedAppointments) {
      if (appointment.status === 'Cancelled') continue;
      const key = appointment.appointment_date_key;
      const day = byDate.get(key);
      if (!day) continue;
      const doctorId = idText(appointment.doctor_id);
      let doctorDay = (day.doctors || []).find((row) => idText(row.doctorId) === doctorId);
      if (!doctorDay) {
        doctorDay = { doctorId: appointment.doctor_id, bookedAppointments: [], bookedPatients: [], breaks: [] };
        day.doctors.push(doctorDay);
      }

      if (appointment.type === 'time-based' && appointment.start_time && appointment.end_time) {
        doctorDay.bookedAppointments.push({
          startTime: new Date(appointment.start_time),
          endTime: new Date(appointment.end_time),
          duration: Number(appointment.duration || 10),
          appointmentId: appointment._id,
          status: appointment.status === 'In Progress' ? 'InProgress' : appointment.status
        });
        calendarSummary.reservationsRebuilt += 1;
      } else if (appointment.type === 'number-based') {
        doctorDay.bookedPatients.push({
          patientId: appointment.patient_id,
          serialNumber: Number(appointment.serial_number || 1),
          appointmentId: appointment._id
        });
        calendarSummary.reservationsRebuilt += 1;
      }
    }

    const days = [...byDate.values()].sort((a, b) => a.dateKey.localeCompare(b.dateKey));
    calendarSummary.normalizedDays = days.length;
    normalizedCalendar = { days, timezone: timeZone };
  }

  if (APPLY) {
    if (appointmentUpdates.length) {
      await appointmentsCollection.bulkWrite(appointmentUpdates, { ordered: false });
    }
    if (calendar && normalizedCalendar) {
      await calendarsCollection.updateOne(
        { _id: calendar._id, hospitalId },
        { $set: normalizedCalendar }
      );
    }
    await mongoose.connection.collection('hospitals').updateOne(
      { _id: hospitalId },
      { $set: { timezone: timeZone } }
    );
  }

  return {
    hospitalId: idText(hospitalId),
    hospitalName: hospital.hospitalName || hospital.name,
    timeZone,
    mode: APPLY ? 'APPLY' : 'DRY_RUN',
    appointmentsScanned: appointments.length,
    appointmentsNormalizable: appointmentUpdates.length,
    legacyWallClockCandidates: legacyCandidates,
    calendar: calendarSummary
  };
}

async function main() {
  await mongoose.connect(mongoUri, { autoIndex: false, autoCreate: false, serverSelectionTimeoutMS: 15000 });
  const hospitalsCollection = mongoose.connection.collection('hospitals');
  const hospitalFilter = HOSPITAL_ID ? { _id: new mongoose.Types.ObjectId(HOSPITAL_ID) } : {};
  const hospitals = await hospitalsCollection.find(hospitalFilter).toArray();
  if (!hospitals.length) throw new Error('No hospitals found for the selected scope');

  const results = [];
  for (const hospital of hospitals) {
    // eslint-disable-next-line no-await-in-loop
    const result = await normalizeHospital(hospital);
    results.push(result);
    console.log(JSON.stringify({
      hospitalId: result.hospitalId,
      mode: result.mode,
      timeZone: result.timeZone,
      appointmentsScanned: result.appointmentsScanned,
      legacyWallClockCandidates: result.legacyWallClockCandidates.length,
      calendar: result.calendar
    }, null, 2));
  }

  const report = {
    generatedAt: new Date().toISOString(),
    apply: APPLY,
    repairLegacyWallClock: REPAIR_LEGACY_WALL_CLOCK,
    repairSources: [...REPAIR_SOURCES],
    results
  };
  if (REPORT_PATH) {
    fs.writeFileSync(REPORT_PATH, `${JSON.stringify(report, null, 2)}\n`);
    console.log(`Report written to ${REPORT_PATH}`);
  }

  if (!APPLY) console.log('DRY RUN ONLY: no database records were changed. Re-run with --apply after reviewing the report.');
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await mongoose.connection.close().catch(() => {});
  });
