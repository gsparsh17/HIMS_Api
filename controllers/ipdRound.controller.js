const { assertAdmissionOpenForMutation } = require('../services/ipdLifecycleGuard.service');

function money(value) { return Number(Number(value || 0).toFixed(2)); }
function clientKey(req) {
  return String(req.body?.idempotencyKey || req.get?.('Idempotency-Key') || '').trim() || null;
}
function chargeKey(hospitalId, roundId) { return `${hospitalId}:DoctorRound:${roundId}:charge`; }

function assertAdmissionOpenForClinicalMutation(admission) {
  return assertAdmissionOpenForMutation(admission, { action: 'Ward-round activity' });
}

async function updateAdmissionTotals(admissionId, hospitalId, session = null) {
  const charges = await IPDCharge.find({ admissionId, hospitalId, is_active: { $ne: false }, status: { $ne: 'VOIDED' } }).session(session || null);
  const totalBillAmount = money(charges.reduce((sum, c) => sum + Number(c.netAmount || 0), 0));
  const admission = await IPDAdmission.findOne({ _id: admissionId, hospitalId, is_active: { $ne: false } }).session(session || null);
  if (admission) {
    admission.totalBillAmount = totalBillAmount;
    admission.dueAmount = money(totalBillAmount - Number(admission.paidAmount || 0));
    await admission.save({ session: session || undefined });
  }
  return totalBillAmount;
}

async function buildDoctorRoundCharge({ req, admission, round, session, isAutoGenerated = true }) {
  const tariff = await resolveDoctorTariff({
    hospitalId: admission.hospitalId,
    doctorId: round.doctorId,
    encounterType: 'IPD',
    visitType: 'ROUND',
    admissionId: admission._id,
    serviceDate: round.roundDateTime,
  });
  const q = tariff.quote || {};
  const amounts = q.amounts || {};
  const patientBefore = Number(amounts.patientLiability ?? amounts.contracted ?? tariff.amount ?? 0);
  const sponsorBefore = Number(amounts.sponsorLiability || 0);
  const contracted = Number(amounts.contracted ?? tariff.amount ?? patientBefore + sponsorBefore);
  const policy = await resolveFinancialPolicy({
    hospitalId: admission.hospitalId,
    user: req.user,
    encounterType: 'IPD',
    serviceType: 'CONSULTATION',
    serviceCode: q.serviceCode || 'DOCTOR_ROUND',
    payerCategory: admission.sponsorType && admission.sponsorType !== 'self' ? 'SPONSOR' : 'SELF',
    departmentId: admission.departmentId,
    selectedMode: admission.selectedBillingMode || undefined,
    patientLiability: patientBefore,
    sponsorLiability: sponsorBefore,
    contractedAmount: contracted,
    adjustments: {},
  });
  const a = policy.amounts;
  const rate = money(a.grossAmount || contracted);
  const description = `Doctor round on ${new Date(round.roundDateTime).toLocaleDateString('en-IN')} - ${round.patientCondition || 'Routine visit'}`;
  const pricingSnapshot = {
    rateCardId: q.rateCard?.id || null,
    rateCardVersion: q.rateCard?.version || null,
    rateCardItemId: q.rateCardItemId || null,
    serviceCode: q.serviceCode || 'DOCTOR_ROUND',
    resultType: q.resultType || 'self',
    inputs: { ...(q.inputs || {}), doctorId: round.doctorId, encounterType: 'IPD', visitType: 'ROUND', wardEntitlement: tariff.wardEntitlement },
    amounts: {
      hospitalStandard: Number(amounts.hospitalStandard ?? rate),
      contracted: Number(a.netAmount ?? contracted),
      eligible: Number(amounts.eligible ?? contracted),
      sponsorLiability: Number(a.sponsorLiability || 0),
      patientLiability: Number(a.patientLiability || 0),
      nonAdmissible: Number(amounts.nonAdmissible || 0),
      hospitalAdjustment: Number(amounts.hospitalAdjustment || 0),
      hospitalConcession: Number(amounts.hospitalConcession || 0) + Number(a.discountAmount || 0),
      packageAbsorbed: Number(amounts.packageAbsorbed || 0),
    },
    explanation: [...(q.explanation || []), 'Doctor tariff resolved server-side; payroll amount was not used'],
    ruleTrace: q.ruleTrace || [],
    pricedAt: operationNow(),
  };
  const charge = new IPDCharge({
    hospitalId: admission.hospitalId,
    admissionId: admission._id,
    patientId: admission.patientId,
    chargeType: 'Doctor Visit',
    description,
    quantity: 1,
    rate,
    discountType: a.discountType || 'fixed',
    discountRate: a.discountRate || 0,
    discountAmount: a.discountAmount || 0,
    discountReason: a.discountReason || undefined,
    taxMode: a.taxMode || 'exempt',
    taxName: a.taxName || undefined,
    taxCode: a.taxCode || undefined,
    taxRate: a.taxRate || 0,
    taxAmount: a.taxAmount || 0,
    taxExemptionReason: a.taxExemptionReason || undefined,
    sourceModule: 'DoctorRound',
    sourceId: round._id,
    sourceReference: { module: 'DoctorVisit', documentId: round._id, lineKey: `DoctorRound:${round._id}` },
    idempotencyKey: chargeKey(admission.hospitalId, round._id),
    isAutoGenerated,
    chargeDateKey: hospitalDateKey(round.roundDateTime || operationNow()),
    isBilled: false,
    addedBy: req.user?._id,
    notes: round.notes || undefined,
    pricingSnapshot,
    financialPolicySnapshot: policy.policySnapshot,
    selectedBillingMode: policy.selectedMode,
    requiredNowAmount: policy.requiredNow,
    clearanceState: policy.clearanceState,
  });
  await charge.save({ session });
  await IPDAdmission.updateOne(
    { _id: admission._id, hospitalId: admission.hospitalId },
    {
      $set: { financialClearanceStatus: 'in_progress' },
      $unset: { financialClearedAt: 1, financialClearedBy: 1, finalSettlementReceiptNumber: 1 }
    },
    session ? { session } : undefined
  );
  return { charge, policy, tariff };
}

exports.getDoctorTariff = async (req, res) => {
  try {
    const hospitalId = requestHospitalId(req);
    const { admissionId, doctorId } = req.query;
    const admission = await IPDAdmission.findOne({ _id: admissionId, hospitalId, is_active: { $ne: false } }).lean();
    if (!admission) return res.status(404).json({ error: 'Admission not found' });
    const tariff = await resolveDoctorTariff({ hospitalId, doctorId: doctorId || admission.primaryDoctorId, encounterType: 'IPD', visitType: 'ROUND', admissionId });
    const amounts = tariff.quote?.amounts || {};
    const policy = await resolveFinancialPolicy({
      hospitalId, user: req.user, encounterType: 'IPD', serviceType: 'CONSULTATION',
      serviceCode: tariff.quote?.serviceCode || 'DOCTOR_ROUND', departmentId: admission.departmentId,
      selectedMode: admission.selectedBillingMode || undefined,
      patientLiability: Number(amounts.patientLiability ?? tariff.amount ?? 0),
      sponsorLiability: Number(amounts.sponsorLiability || 0),
      contractedAmount: Number(amounts.contracted ?? tariff.amount ?? 0), adjustments: {}
    });
    const workflowPolicy = await loadIPDWorkflowPolicy(hospitalId);
    return res.json({ success: true, tariff: { ...tariff, financialPolicy: policy }, doctorRoundCharging: workflowPolicy.doctorRoundCharging });
  } catch (err) {
    return res.status(err.statusCode || 500).json({ error: err.message, code: err.code });
  }
};

exports.createRound = async (req, res) => {
  const hospitalId = requestHospitalId(req);
  const key = clientKey(req);
  const {
    admissionId, patientId, doctorId, roundDateTime, patientCondition, complaints, symptoms,
    examinationFindings, dailyHistoryAndExamination, diagnosis, treatmentPlan, medicationChanges,
    advice, dischargeSuggested, painScore, notes, templateId, copiedFromRoundId, safetyChecklist,
    vitalId, vitalSnapshot, dischargeAssessment,
  } = req.body || {};

  try {
    const lookupSession = req.transactionSession || null;
    if (key) {
      const existingQuery = IPDRound.findOne({ hospitalId, idempotencyKey: key, is_active: { $ne: false } });
      if (lookupSession) existingQuery.session(lookupSession);
      const existing = await existingQuery;
      if (existing) {
        const chargeQuery = IPDCharge.findOne({ hospitalId, sourceModule: 'DoctorRound', sourceId: existing._id, is_active: { $ne: false } });
        if (lookupSession) chargeQuery.session(lookupSession);
        const charge = await chargeQuery;
        return res.status(200).json({ success: true, reused: true, round: existing, charge });
      }
    }

    const externalSession = req.transactionSession || null;
    const session = externalSession || await mongoose.startSession();
    let result;
    const execute = async () => {
      const admission = await IPDAdmission.findOne({ _id: admissionId, hospitalId, is_active: { $ne: false } }).session(session);
      if (!admission) throw Object.assign(new Error('Admission not found'), { statusCode: 404 });
      assertAdmissionOpenForClinicalMutation(admission);
      if (patientId && String(patientId) !== String(admission.patientId)) throw Object.assign(new Error('Patient does not match admission'), { statusCode: 409 });

      const round = new IPDRound({
        hospitalId, admissionId: admission._id, patientId: admission.patientId, doctorId,
        roundDateTime: roundDateTime || operationNow(), patientCondition, complaints, symptoms,
        examinationFindings, dailyHistoryAndExamination, diagnosis, treatmentPlan, medicationChanges,
        advice, dischargeSuggested, painScore, notes, templateId: templateId || null,
        copiedFromRoundId: copiedFromRoundId || null, safetyChecklist, vitalId, vitalSnapshot,
        dischargeAssessment, createdBy: req.user?._id, idempotencyKey: key,
      });
      await round.save({ session });
      const workflowPolicy = await loadIPDWorkflowPolicy(hospitalId);
      const roundChargingMode = workflowPolicy.doctorRoundCharging.mode;
      let charge = null;
      let policy = null;
      if (roundChargingMode === 'AUTO_PER_ROUND') {
        ({ charge, policy } = await buildDoctorRoundCharge({ req, admission, round, session, isAutoGenerated: true }));
      } else if (roundChargingMode === 'ONCE_PER_DAY') {
        const dateKey = hospitalDateKey(round.roundDateTime || operationNow());
        charge = await IPDCharge.findOne({
          hospitalId,
          admissionId: admission._id,
          sourceModule: 'DoctorRound',
          chargeDateKey: dateKey,
          status: { $nin: ['VOIDED', 'CANCELLED'] },
          is_active: { $ne: false }
        }).session(session);
        if (!charge) ({ charge, policy } = await buildDoctorRoundCharge({ req, admission, round, session, isAutoGenerated: true }));
      }
      await updateAdmissionTotals(admission._id, hospitalId, session);
      if (dischargeSuggested && admission.canProceedToDischarge) {
        admission.status = 'Discharge Initiated';
        await admission.save({ session });
      }
      result = { round, charge, financialPolicy: policy, doctorRoundCharging: workflowPolicy.doctorRoundCharging };
    };

    try {
      if (externalSession) await execute();
      else await session.withTransaction(execute);
    } finally {
      if (!externalSession) await session.endSession();
    }
    return res.status(201).json({ success: true, message: 'Round note added successfully', ...result });
  } catch (err) {
    if (err?.code === 11000 && key) {
      const existing = await IPDRound.findOne({ hospitalId, idempotencyKey: key, is_active: { $ne: false } });
      const charge = existing ? await IPDCharge.findOne({ hospitalId, sourceModule: 'DoctorRound', sourceId: existing._id, is_active: { $ne: false } }) : null;
      if (existing) return res.status(200).json({ success: true, reused: true, round: existing, charge });
    }
    console.error('Error creating round:', err);
    return res.status(err.statusCode || 500).json({ error: err.message, code: err.code });
  }
};


function captureControllerResponse() {
  return {
    statusCode: 200,
    body: null,
    status(code) { this.statusCode = code; return this; },
    json(payload) { this.body = payload; return this; },
    send(payload) { this.body = payload; return this; }
  };
}

function throwCapturedFailure(capture, fallbackMessage) {
  if (capture.statusCode < 400) return;
  const error = new Error(capture.body?.error || capture.body?.message || fallbackMessage);
  error.statusCode = capture.statusCode;
  error.code = capture.body?.code;
  error.details = capture.body;
  throw error;
}

// One server-side command for a complete doctor ward-round event. Round note +
// automatic doctor charge + existing-medication mutations + prescription/
// investigation/MAR/pharmacy requests all share one Mongo transaction. A retry
// reuses the round/order idempotency keys and never commits a partial bundle.
exports.completeIPDRound = async (req, res) => {
  const hospitalId = requestHospitalId(req);
  const body = req.body || {};
  const roundPayload = body.round || {};
  const medicationChanges = Array.isArray(body.medicationChanges) ? body.medicationChanges : [];
  const prescriptionPayload = body.prescription || null;
  const commandKey = String(body.idempotencyKey || roundPayload.idempotencyKey || req.get?.('Idempotency-Key') || '').trim();
  if (!commandKey) return res.status(400).json({ error: 'Idempotency-Key is required for complete ward-round submission', code: 'ROUND_COMMAND_IDEMPOTENCY_REQUIRED' });

  const session = await mongoose.startSession();
  try {
    let result;
    await session.withTransaction(async () => {
      const roundReq = Object.assign(Object.create(req), {
        body: { ...roundPayload, idempotencyKey: commandKey },
        transactionSession: session
      });
      const roundRes = captureControllerResponse();
      await exports.createRound(roundReq, roundRes);
      throwCapturedFailure(roundRes, 'Unable to save ward round');
      const round = roundRes.body?.round;
      if (!round?._id) throw Object.assign(new Error('Ward round was not returned by the round command'), { statusCode: 500 });

      const medicationResults = [];
      if (medicationChanges.length) {
        const medicationController = require('./ipdMedication.controller');
        for (const row of medicationChanges) {
          if (!row?.medicationId) throw Object.assign(new Error('Every medication change requires medicationId'), { statusCode: 400 });
          const medReq = Object.assign(Object.create(req), {
            params: { ...(req.params || {}), id: row.medicationId },
            body: { ...(row.change || row), medicationId: undefined, change: undefined, roundId: round._id },
            transactionSession: session
          });
          const medRes = captureControllerResponse();
          await medicationController.changeMedicationOrder(medReq, medRes);
          throwCapturedFailure(medRes, 'Unable to apply medication change');
          medicationResults.push({ medicationId: row.medicationId, ...medRes.body });
        }
      }

      let prescriptionResult = null;
      if (prescriptionPayload) {
        const hasOrders = Boolean(
          (prescriptionPayload.items || []).length ||
          (prescriptionPayload.lab_test_requests || []).length ||
          (prescriptionPayload.radiology_test_requests || []).length ||
          (prescriptionPayload.procedure_requests || []).length
        );
        if (hasOrders) {
          const prescriptionController = require('./prescription.controller');
          const prescriptionReq = Object.assign(Object.create(req), {
            body: {
              ...prescriptionPayload,
              source_type: 'IPD',
              ipd_admission_id: round.admissionId,
              patient_id: round.patientId,
              doctor_id: round.doctorId,
              round_id: round._id
            },
            transactionSession: session
          });
          const prescriptionRes = captureControllerResponse();
          await prescriptionController.createPrescription(prescriptionReq, prescriptionRes);
          throwCapturedFailure(prescriptionRes, 'Unable to save ward-round orders');
          prescriptionResult = prescriptionRes.body;
        }
      }

      result = {
        round: roundRes.body,
        medicationChanges: medicationResults,
        prescription: prescriptionResult
      };
    });
    return res.status(201).json({ success: true, message: 'Ward round and all linked clinical orders committed atomically', commandIdempotencyKey: commandKey, ...result });
  } catch (error) {
    console.error('Atomic ward-round command failed:', error);
    return res.status(error.statusCode || 500).json({ error: error.message, code: error.code, details: error.details });
  } finally {
    await session.endSession();
  }
};

exports.postRoundCharge = async (req, res) => {
  const hospitalId = requestHospitalId(req);
  try {
    const workflowPolicy = await loadIPDWorkflowPolicy(hospitalId);
    if (workflowPolicy.doctorRoundCharging.mode === 'DISABLED') {
      return res.status(409).json({ error: 'Doctor round billing is disabled by hospital policy.' });
    }
    if (workflowPolicy.doctorRoundCharging.mode !== 'MANUAL') {
      const existing = await IPDCharge.findOne({ hospitalId, sourceModule: 'DoctorRound', sourceId: req.params.id, is_active: { $ne: false }, status: { $nin: ['VOIDED', 'CANCELLED'] } });
      if (existing) return res.json({ success: true, alreadyExists: true, charge: existing, doctorRoundCharging: workflowPolicy.doctorRoundCharging });
      return res.status(409).json({ error: `Manual doctor-round charging is unavailable while mode is ${workflowPolicy.doctorRoundCharging.mode}.` });
    }

    const existing = await IPDCharge.findOne({ hospitalId, sourceModule: 'DoctorRound', sourceId: req.params.id, is_active: { $ne: false }, status: { $nin: ['VOIDED', 'CANCELLED'] } });
    if (existing) return res.json({ success: true, alreadyExists: true, charge: existing, doctorRoundCharging: workflowPolicy.doctorRoundCharging });

    const round = await IPDRound.findOne({ _id: req.params.id, hospitalId, is_active: { $ne: false } });
    if (!round) return res.status(404).json({ error: 'Round not found' });
    const admission = await IPDAdmission.findOne({ _id: round.admissionId, hospitalId, is_active: { $ne: false } });
    if (!admission) return res.status(404).json({ error: 'Admission not found' });
    assertAdmissionOpenForClinicalMutation(admission);

    const { charge, policy } = await buildDoctorRoundCharge({ req, admission, round, session: null, isAutoGenerated: false });
    await updateAdmissionTotals(admission._id, hospitalId);
    return res.status(201).json({ success: true, charge, financialPolicy: policy, doctorRoundCharging: workflowPolicy.doctorRoundCharging });
  } catch (err) {
    if (err?.code === 11000) {
      const existing = await IPDCharge.findOne({ hospitalId, sourceModule: 'DoctorRound', sourceId: req.params.id, is_active: { $ne: false } });
      if (existing) return res.json({ success: true, alreadyExists: true, charge: existing });
    }
    return res.status(err.statusCode || 500).json({ error: err.message, code: err.code });
  }
};

exports.getRoundsByAdmission = async (req, res) => {
  try {
    const hospitalId = requestHospitalId(req);
    const rounds = await IPDRound.find({ hospitalId, admissionId: req.params.admissionId, is_active: { $ne: false } })
      .populate('doctorId', 'firstName lastName specialization')
      .populate({ path: 'prescriptionId', select: 'diagnosis items lab_test_requests radiology_test_requests procedure_requests issue_date createdAt' })
      .populate('templateId', 'name diseaseName templateType')
      .populate('copiedFromRoundId', 'roundDateTime diagnosis').sort({ roundDateTime: -1 }).lean();
    const roundIds = rounds.map((row) => row._id);
    const charges = roundIds.length
      ? await IPDCharge.find({ hospitalId, sourceModule: 'DoctorRound', sourceId: { $in: roundIds }, is_active: { $ne: false }, status: { $nin: ['VOIDED', 'CANCELLED'] } }).lean()
      : [];
    const chargeByRound = new Map(charges.map((charge) => [String(charge.sourceId), charge]));
    const workflowPolicy = await loadIPDWorkflowPolicy(hospitalId);
    res.json({
      success: true,
      doctorRoundCharging: workflowPolicy.doctorRoundCharging,
      rounds: rounds.map((round) => ({ ...round, charge: chargeByRound.get(String(round._id)) || null }))
    });
  } catch (err) { res.status(err.statusCode || 500).json({ error: err.message }); }
};

